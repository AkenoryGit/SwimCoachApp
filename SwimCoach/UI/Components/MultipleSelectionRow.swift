// Этот файл содержит пользовательский элемент интерфейса, который позволяет выбирать пункты из списка с возможностью множественного выбора.
// Например, такой элемент можно использовать, когда надо выбрать сразу нескольких клиентов или несколько опций.

import SwiftUI

// Объявляем структуру (это как мини-компонент), которая создаёт одну строку со встроенной логикой выбора.
struct MultipleSelectionRow: View {
    // Название этой строки — текст, который будет показан слева
    var title: String
    
    // Флаг (булево значение), указывающий, выбрана ли эта строка или нет
    var isSelected: Bool
    
    // Действие, которое произойдёт при нажатии на строку — сюда можно передать любую функцию
    var action: () -> Void

    // Основная часть отображения (что увидит пользователь)
    var body: some View {
        // Кнопка — она реагирует на нажатие
        Button(action: self.action) {
            // Горизонтальное размещение: текст слева, значок справа
            HStack {
                // Показываем текст заголовка
                Text(title)
                
                // Spacer — вставляет пустое пространство между текстом и галочкой (если она есть)
                Spacer()
                
                // Если строка выбрана (isSelected = true), показываем иконку "галочка"
                if self.isSelected {
                    Image(systemName: "checkmark") // системная иконка с галочкой
                }
            }
        }
    }
}

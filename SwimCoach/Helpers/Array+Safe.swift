import SwiftUI

// Это расширение для массива добавляет безопасный способ доступа к элементам по индексу.
// Обычно, если ты попытаешься взять элемент массива по несуществующему индексу, приложение «упадёт» (crash).
// С этим расширением, если индекс неправильный (например, выходит за границы массива), то вернётся nil, а не ошибка.
//
// Пример:
// let numbers = [10, 20, 30]
// numbers[1] вернёт 20
// numbers[5] вызовет ошибку (если использовать обычный способ)
// numbers[safe: 5] вернёт nil и приложение продолжит работать без сбоев
//
// Это очень полезно, когда ты не уверен, есть ли элемент в массиве по какому-то индексу.
extension Array {
    subscript(safe index: Int) -> Element? {
        indices.contains(index) ? self[index] : nil
    }
}

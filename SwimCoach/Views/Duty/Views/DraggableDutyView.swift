import SwiftUI

// Этот компонент отображает визуальное представление одного блока "Дежурство"
// в расписании. Используется внутри временной шкалы (таймлайна).
struct DraggableDutyView: View {
    // Дежурство, которое нужно отобразить
    let duty: Duty

    // Смещение блока по вертикали от верхнего края таймлайна
    let topOffset: CGFloat

    // Высота блока на экране (зависит от длительности дежурства)
    let height: CGFloat

    var body: some View {
        // Прямоугольник с закруглёнными углами, залитый оранжевым цветом
        RoundedRectangle(cornerRadius: 8) // Используем RoundedRectangle для мягких краёв
            .fill(Color.orange.opacity(0.8)) // Прозрачность 80% для визуальной мягкости
            .frame(width: 60, height: height) // Ширина фиксированная, высота задаётся параметром

            // Наложение текста поверх прямоугольника
            .overlay(
                VStack(alignment: .leading, spacing: 4) { // Текст выравнивается по левому краю, отступы между строками — 4
                    Text("Дежурство") // Заголовок
                        .font(.caption) // Размер шрифта для заголовка
                        .bold() // Жирный шрифт для выделения заголовка
                        .foregroundColor(.white) // Белый цвет текста на оранжевом фоне

                    // Если есть заметка к дежурству — показать её
                    if let note = duty.note, !note.isEmpty {
                        Text(note) // Текст заметки
                            .font(.caption2) // Меньший размер шрифта для заметки
                            .foregroundColor(.white) // Белый цвет текста заметки для лучшей читаемости
                            .lineLimit(2) // Показываем максимум 2 строки
                    }
                }
                .padding(4), // Внутренние отступы
                alignment: .topLeading // Расположение содержимого в верхнем левом углу прямоугольника
            )
            .offset(y: topOffset) // Смещение блока вниз на нужную высоту
    }
}

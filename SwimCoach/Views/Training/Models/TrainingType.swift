import Foundation

// Перечисление всех возможных типов тренировок.
// Это фиксированный список, который используется в приложении:
// - при добавлении новых тренировок (выбор типа)
// - при отображении тренировок (например, на экране расписания)
// - при фильтрации или учёте тренировок
enum TrainingType: String, CaseIterable, Identifiable {
    
    // Персональная тренировка
    case personal = "Персональная"
    
    // Групповая тренировка
    case group = "Группа"
    
    // Мини-группа (от 3-х до 5-ти человек)
    case miniGroup = "Мини-группа"
    
    // Сплит (тренировка с двумя клиентами)
    case split = "Сплит"
    
    // Грудничковое плавание (отдельный формат для младенцев)
    case infant = "Грудничковое плавание"
    
    // Детский бассейн (занятия для детей 3-6 лет)
    case babyPool = "Детский бассейн"
    
    // СПТ — стартовая персональная тренировка
    case startingTraining = "СПТ"

    // Свойство `id` используется для соответствия протоколу `Identifiable`.
    // Это нужно для использования в SwiftUI в `ForEach`, `Picker` и т.п.
    var id: String { self.rawValue }

}

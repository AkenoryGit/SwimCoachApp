import Foundation

// Этот код описывает список возможных мест, где могут проходить тренировки.
// Мы используем перечисление (enum), чтобы определить конкретные варианты: большой бассейн, малый бассейн и тренажёрный зал.
// Это помогает не допускать ошибок при выборе места и удобно использовать в интерфейсе SwiftUI.

enum TrainingLocation: String, CaseIterable, Identifiable {
    // Большой бассейн (сокращение: ББ)
    case bigPool = "ББ"

    // Малый бассейн (сокращение: ДБ)
    case smallPool = "ДБ"

    // Тренажёрный зал (сокращение: ТЗ)
    case gym = "ТЗ"

    // Это нужно для SwiftUI — чтобы каждое значение enum можно было использовать в списках (например, в Picker)
    // Возвращаем уникальный идентификатор, которым будет само сокращение (например, "ББ")
    var id: String { self.rawValue }
}
